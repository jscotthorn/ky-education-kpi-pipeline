"""Lock the committed Title I flag list.

The list is generated by ``scripts/build_b_flagged_keys.py`` from the
registered raw files. This test reads the committed CSV. It does not
rebuild it. Rector A. Jones ``035020`` is the issue #64 example: 2022
Title I Non-White 5.65 and White -5.40 (stored -5.4).
"""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLAG_PATH = ROOT / "notes" / "flags" / "B-flagged-keys.csv"
REASONS = {
    "absolute-value gap year",
    "negative complement cell",
    "paired complement cell",
    "UAT-negated gap",
}


def _rows() -> list[dict[str, str]]:
    with FLAG_PATH.open(newline="") as handle:
        reader = csv.DictReader(handle)
        assert reader.fieldnames == [
            "module",
            "year",
            "district",
            "school_id",
            "student_group",
            "metric",
            "value",
            "reason",
            "label",
        ]
        return list(reader)


def test_flag_list_counts_and_rector_pair() -> None:
    rows = _rows()
    assert len(rows) == 6488
    reasons = Counter(row["reason"] for row in rows)
    assert reasons["absolute-value gap year"] == 6408
    assert reasons["negative complement cell"] == 40
    assert reasons["paired complement cell"] == 40
    assert reasons["UAT-negated gap"] == 0
    assert set(reasons) <= REASONS
    assert {row["label"] for row in rows} == {"kde-recheck"}
    complements = [
        row for row in rows if row["reason"] in {"negative complement cell", "paired complement cell"}
    ]
    by_year = Counter(row["year"] for row in complements)
    assert by_year == {"2022": 60, "2023": 20}
    rector = [
        row
        for row in rows
        if row["school_id"] == "035020"
        and row["year"] == "2022"
        and row["student_group"] in {"Non-White", "White (non-Hispanic)"}
    ]
    assert {(row["student_group"], row["value"], row["reason"]) for row in rector} == {
        ("Non-White", "5.65", "paired complement cell"),
        ("White (non-Hispanic)", "-5.4", "negative complement cell"),
    }
